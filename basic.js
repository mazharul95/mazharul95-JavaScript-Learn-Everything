//keywords are reserved words that have a special meaning in the language. You cannot normally use them as variable, function, or class names.


// Keyword	Purpose
// let	Declares a variable
// const	Declares a constant
// var	Declares a variable (older syntax)
// if	Creates a condition
// else	Executes when if is false
// for	Creates a loop
// while	Creates a loop
// function	Declares a function
// return	Returns a value from a function
// class	Defines a class
// new	Creates an object from a constructor/class
// this	Refers to the current context/object
// switch	Handles multiple conditions
// case	Defines a condition inside switch
// break	Stops a loop or switch
// continue	Skips the current loop iteration
// try	Starts error-handling code
// catch	Handles an error
// throw	Throws an error
// async	Declares an asynchronous function
// await	Waits for a Promise
// import	Imports modules
// export	Exports modules
// typeof	Checks a value's data type
// instanceof	Checks an object's type



// In short:
// JavaScript keywords are reserved words that tell the JavaScript engine what to do.